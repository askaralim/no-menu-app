#!/usr/bin/env node
// Pull REAL published Tap List data from production (public, anon-only RPCs)
// and emit a SQL load script for the LOCAL Supabase database.
//
// Safe: read-only against production, uses only the public anon RPCs the
// consumer app already calls. No service-role key or DB password required.
//
// Usage:
//   node supabase/tools/import-prod-public-data.mjs > supabase/tools/prod_public_import.sql
//
// Then apply to local:
//   docker exec -i supabase_db_no-menu-app psql -U postgres -d postgres \
//     < supabase/tools/prod_public_import.sql

const PROD_URL = process.env.PROD_SUPABASE_URL || 'https://agtujigvxxdppngirqtu.supabase.co'
const PROD_ANON =
  process.env.PROD_SUPABASE_ANON_KEY ||
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImFndHVqaWd2eHhkcHBuZ2lycXR1Iiwicm9sZSI6ImFub24iLCJpYXQiOjE3NjcwMDg4NDAsImV4cCI6MjA4MjU4NDg0MH0.GUHpaSWrXVgvkj-Y8f0TMmrwog_Ir-7pVoFNpFk8fcI'

const STATUS_ZH_TO_ENUM = {
  上新: 'new',
  在售: 'available',
  少量: 'low',
  售罄: 'sold_out',
  即将上新: 'coming_soon',
  即将上枪: 'coming_soon',
}

async function rpc(fn, args = {}) {
  const res = await fetch(`${PROD_URL}/rest/v1/rpc/${fn}`, {
    method: 'POST',
    headers: {
      apikey: PROD_ANON,
      Authorization: `Bearer ${PROD_ANON}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(args),
  })
  if (!res.ok) {
    throw new Error(`${fn} -> HTTP ${res.status}: ${await res.text()}`)
  }
  return res.json()
}

// SQL literal helpers.
const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
const n = (v) => (v === null || v === undefined || v === '' || Number.isNaN(Number(v)) ? 'NULL' : String(Number(v)))
const b = (v) => (v ? 'true' : 'false')
// jsonb literal: encode objects/arrays as valid JSON, cast to jsonb.
const j = (v) =>
  v === null || v === undefined ? 'NULL' : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`

async function main() {
  const out = []
  const log = (...m) => process.stderr.write(m.join(' ') + '\n')

  const citiesPayload = await rpc('get_public_taplist_cities')
  const cities = citiesPayload?.cities ?? []
  log(`cities: ${cities.map((c) => `${c.city}(${c.bar_count})`).join(', ')}`)

  let tenantCount = 0
  let drinkCount = 0

  out.push('-- Generated by import-prod-public-data.mjs')
  out.push(`-- Source: ${PROD_URL} (public anon RPCs, read-only)`)
  out.push(`-- Generated at: ${new Date().toISOString()}`)
  out.push('BEGIN;')
  out.push('')

  const seenTenants = new Set()

  for (const c of cities) {
    const bars = await rpc('get_public_taplist_bars', { p_city: c.city })
    log(`  ${c.city}: ${bars.length} bars`)

    for (const bar of bars) {
      if (seenTenants.has(bar.id)) continue
      seenTenants.add(bar.id)

      const drinksPayload = await rpc('get_public_taplist_drinks', { p_tenant_id: bar.id })
      const drinks = drinksPayload?.ok ? drinksPayload.drinks ?? [] : []

      tenantCount++
      drinkCount += drinks.length
      log(`    ${bar.display_name || bar.name}: ${drinks.length} drinks`)

      // Per-tenant DO block: reuse an existing local tenant with the same slug
      // (preserving its id + owner membership) or insert under production's id.
      const catIds = [...new Set(drinks.map((d) => d.category_id).filter(Boolean))]
      const fallbackCat = catIds[0] || null
      const body = []

      body.push(`  SELECT id INTO v_tid FROM public.tenants WHERE slug = ${q(bar.slug)} LIMIT 1;`)
      body.push('  IF v_tid IS NULL THEN')
      body.push(`    v_tid := ${q(bar.id)};`)
      body.push(
        `    INSERT INTO public.tenants (id, name, slug, display_name, district, address, opening_hour, description, cover_image_url, city, country, status, is_public_visible, last_menu_updated_at)
    VALUES (v_tid, ${q(bar.name)}, ${q(bar.slug)}, ${q(bar.display_name)}, ${q(bar.district)}, ${q(bar.address)}, ${j(bar.opening_hour)}, ${q(bar.description)}, ${q(bar.cover_image_url)}, ${q(bar.city)}, ${q(bar.country)}, 'active', true, ${q(bar.last_menu_updated_at)});`,
      )
      body.push('  ELSE')
      body.push(
        `    UPDATE public.tenants SET
      name = ${q(bar.name)}, display_name = ${q(bar.display_name)}, district = ${q(bar.district)},
      address = ${q(bar.address)}, opening_hour = ${j(bar.opening_hour)}, description = ${q(bar.description)},
      cover_image_url = ${q(bar.cover_image_url)}, city = ${q(bar.city)}, country = ${q(bar.country)},
      status = 'active', is_public_visible = true, last_menu_updated_at = ${q(bar.last_menu_updated_at)}
    WHERE id = v_tid;`,
      )
      body.push('  END IF;')

      // Refresh this tenant's menu from scratch (INIT pattern).
      body.push('  DELETE FROM public.drink_serving_options WHERE tenant_id = v_tid;')
      body.push('  DELETE FROM public.drink_beer_profiles WHERE tenant_id = v_tid;')
      body.push('  DELETE FROM public.drinks WHERE tenant_id = v_tid;')
      body.push('  DELETE FROM public.categories WHERE tenant_id = v_tid;')

      catIds.forEach((catId, i) => {
        body.push(
          `  INSERT INTO public.categories (id, tenant_id, name, sort_order, enabled, is_public_visible) VALUES (${q(catId)}, v_tid, ${q(catIds.length > 1 ? `酒单 ${i + 1}` : '酒单')}, ${i + 1}, true, true);`,
        )
      })

      drinks.forEach((d, i) => {
        const beer = d.beer || {}
        const servings = Array.isArray(d.serving_options) ? d.serving_options : []
        const defaultServing = servings.find((s) => s.is_default) || servings[0]
        const price = defaultServing && defaultServing.price != null ? Number(defaultServing.price) : 0
        const status = STATUS_ZH_TO_ENUM[d.public_status] || 'available'
        const catId = d.category_id || fallbackCat
        if (!catId) return

        body.push(
          `  INSERT INTO public.drinks (id, tenant_id, category_id, brand_name, name, image_url, price, price_unit, sort_order, enabled, is_public_visible, public_status, public_sort_order)
  VALUES (${q(d.id)}, v_tid, ${q(catId)}, ${q(d.brand_name)}, ${q(d.name)}, ${q(d.image_url)}, ${n(price)}, '杯', ${n(d.public_sort_order ?? i)}, true, true, ${q(status)}, ${n(d.public_sort_order ?? i)});`,
        )

        if (beer.brewery || beer.beer_style || beer.abv != null || beer.country || beer.description || beer.ibu != null) {
          body.push(
            `  INSERT INTO public.drink_beer_profiles (tenant_id, drink_id, brewery, beer_style, abv, ibu, country, description)
  VALUES (v_tid, ${q(d.id)}, ${q(beer.brewery)}, ${q(beer.beer_style)}, ${n(beer.abv)}, ${n(beer.ibu)}, ${q(beer.country)}, ${q(beer.description)});`,
          )
        }

        servings.forEach((s, si) => {
          body.push(
            `  INSERT INTO public.drink_serving_options (id, tenant_id, drink_id, serving_type, label, volume_ml, price, is_default, is_active, public_sort_order)
  VALUES (${q(s.id)}, v_tid, ${q(d.id)}, ${q(s.serving_type || 'draft')}, ${q(s.label || '杯')}, ${n(s.volume_ml)}, ${n(s.price != null ? s.price : 0)}, ${b(s.is_default)}, ${b(s.is_active !== false)}, ${n(s.public_sort_order ?? si)});`,
          )
        })
      })

      out.push(`-- ===== ${bar.display_name || bar.name} (${bar.slug}) =====`)
      out.push('DO $imp$')
      out.push('DECLARE v_tid uuid;')
      out.push('BEGIN')
      out.push(body.join('\n'))
      out.push('END $imp$;')
      out.push('')
    }
  }

  out.push('COMMIT;')
  out.push(`-- Imported ${tenantCount} tenants, ${drinkCount} drinks`)
  log(`\nDONE: ${tenantCount} tenants, ${drinkCount} drinks`)

  process.stdout.write(out.join('\n') + '\n')
}

main().catch((e) => {
  process.stderr.write(`ERROR: ${e.message}\n`)
  process.exit(1)
})
