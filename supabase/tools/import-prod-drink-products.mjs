#!/usr/bin/env node
/**
 * Read ~100 drink_products (+ their drink_companies) from PRODUCTION (linked project),
 * then INSERT into LOCAL Supabase. Production is SELECT-only via `supabase db query --linked`.
 *
 * Usage (from repo root):
 *   node supabase/tools/import-prod-drink-products.mjs
 */

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const LIMIT = Number(process.env.IMPORT_LIMIT || 100)
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const OUT_SQL = resolve(ROOT, 'supabase/tools/prod_drink_products_import.sql')

function queryLinked(sql) {
  const out = execFileSync(
    'npx',
    ['supabase', 'db', 'query', '--linked', '-o', 'json', '--agent=no', sql],
    {
      cwd: ROOT,
      encoding: 'utf8',
      maxBuffer: 32 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'pipe'],
    },
  )
  // CLI may print npm warnings before JSON
  const start = out.indexOf('[')
  const startObj = out.indexOf('{')
  const i =
    start === -1 ? startObj : startObj === -1 ? start : Math.min(start, startObj)
  if (i < 0) throw new Error(`No JSON in query output:\n${out.slice(0, 500)}`)
  return JSON.parse(out.slice(i))
}

function q(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL'
  if (Array.isArray(v)) {
    if (v.length === 0) return `'{}'::text[]`
    return `ARRAY[${v.map((x) => q(String(x))).join(', ')}]::text[]`
  }
  return `'${String(v).replace(/'/g, "''")}'`
}

function ts(v) {
  if (!v) return 'NULL'
  return `${q(v)}::timestamptz`
}

function main() {
  console.error(`Fetching up to ${LIMIT} active reviewed drink_products from production (read-only)...`)

  const products = queryLinked(`
    SELECT
      id, name, name_en, aliases, brand_name, brewery, beer_style, abv, ibu,
      country, origin_region, image_url, description, tasting_note, status, source,
      created_at, updated_at, company_id, normalized_key, review_status, review_note,
      beer_verification_status, brewery_verification_status
    FROM public.drink_products
    WHERE status = 'active'
      AND review_status = 'reviewed'
    ORDER BY
      (image_url IS NOT NULL) DESC,
      (brewery IS NOT NULL) DESC,
      updated_at DESC NULLS LAST,
      name
    LIMIT ${LIMIT}
  `)

  console.error(`Got ${products.length} products`)

  const companyIds = [
    ...new Set(products.map((p) => p.company_id).filter(Boolean)),
  ]

  let companies = []
  if (companyIds.length > 0) {
    const idList = companyIds.map((id) => `'${id}'`).join(', ')
    companies = queryLinked(`
      SELECT
        id, normalized_key, canonical_name, canonical_name_en, display_name,
        entity_type, country, country_code, origin_region, raw_country_values,
        confidence, review_status, source, source_note, status, created_at, updated_at
      FROM public.drink_companies
      WHERE id IN (${idList})
    `)
    console.error(`Got ${companies.length} related drink_companies`)
  }

  const lines = []
  lines.push('-- Generated by import-prod-drink-products.mjs')
  lines.push('-- Source: production (supabase db query --linked), READ-ONLY')
  lines.push(`-- Generated at: ${new Date().toISOString()}`)
  lines.push(`-- Products: ${products.length}; Companies: ${companies.length}`)
  lines.push('BEGIN;')
  lines.push('')

  for (const c of companies) {
    lines.push(`INSERT INTO public.drink_companies (
  id, normalized_key, canonical_name, canonical_name_en, display_name,
  entity_type, country, country_code, origin_region, raw_country_values,
  confidence, review_status, source, source_note, status, created_at, updated_at
)
SELECT
  ${q(c.id)}, ${q(c.normalized_key)}, ${q(c.canonical_name)}, ${q(c.canonical_name_en)}, ${q(c.display_name)},
  ${q(c.entity_type)}, ${q(c.country)}, ${q(c.country_code)}, ${q(c.origin_region)}, ${q(c.raw_country_values || [])},
  ${q(c.confidence)}, ${q(c.review_status)}, ${q(c.source)}, ${q(c.source_note)}, ${q(c.status)},
  ${ts(c.created_at)}, ${ts(c.updated_at)}
WHERE NOT EXISTS (
  SELECT 1 FROM public.drink_companies x
  WHERE x.id = ${q(c.id)} OR x.normalized_key = ${q(c.normalized_key)}
);`)
    lines.push('')
  }

  const companyById = new Map(companies.map((c) => [c.id, c]))

  for (const p of products) {
    // created_by omitted (auth.users FK risk). Resolve company via id or normalized_key.
    let companyExpr = 'NULL'
    if (p.company_id && companyById.has(p.company_id)) {
      const c = companyById.get(p.company_id)
      companyExpr = `(
  SELECT id FROM public.drink_companies x
  WHERE x.id = ${q(c.id)} OR x.normalized_key = ${q(c.normalized_key)}
  ORDER BY (x.id = ${q(c.id)}) DESC
  LIMIT 1
)`
    }

    lines.push(`INSERT INTO public.drink_products (
  id, name, name_en, aliases, brand_name, brewery, beer_style, abv, ibu,
  country, origin_region, image_url, description, tasting_note, status, source,
  created_by, created_at, updated_at, company_id, normalized_key, review_status, review_note,
  beer_verification_status, brewery_verification_status
) VALUES (
  ${q(p.id)}, ${q(p.name)}, ${q(p.name_en)}, ${q(p.aliases || [])}, ${q(p.brand_name)}, ${q(p.brewery)},
  ${q(p.beer_style)}, ${q(p.abv)}, ${q(p.ibu)}, ${q(p.country)}, ${q(p.origin_region)},
  ${q(p.image_url)}, ${q(p.description)}, ${q(p.tasting_note)}, ${q(p.status)}, ${q(p.source)},
  NULL, ${ts(p.created_at)}, ${ts(p.updated_at)}, ${companyExpr}, ${q(p.normalized_key)},
  ${q(p.review_status)}, ${q(p.review_note)}, ${q(p.beer_verification_status)},
  ${q(p.brewery_verification_status)}
)
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  name_en = EXCLUDED.name_en,
  aliases = EXCLUDED.aliases,
  brand_name = EXCLUDED.brand_name,
  brewery = EXCLUDED.brewery,
  beer_style = EXCLUDED.beer_style,
  abv = EXCLUDED.abv,
  ibu = EXCLUDED.ibu,
  country = EXCLUDED.country,
  origin_region = EXCLUDED.origin_region,
  image_url = EXCLUDED.image_url,
  description = EXCLUDED.description,
  tasting_note = EXCLUDED.tasting_note,
  status = EXCLUDED.status,
  source = EXCLUDED.source,
  company_id = EXCLUDED.company_id,
  normalized_key = COALESCE(EXCLUDED.normalized_key, public.drink_products.normalized_key),
  review_status = EXCLUDED.review_status,
  review_note = EXCLUDED.review_note,
  beer_verification_status = EXCLUDED.beer_verification_status,
  brewery_verification_status = EXCLUDED.brewery_verification_status,
  updated_at = EXCLUDED.updated_at;`)
    lines.push('')
  }

  lines.push('COMMIT;')
  writeFileSync(OUT_SQL, lines.join('\n') + '\n')
  console.error(`Wrote ${OUT_SQL}`)

  console.error('Applying to local supabase_db_no-menu-app...')
  execFileSync(
    'docker',
    ['exec', '-i', 'supabase_db_no-menu-app', 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'],
    {
      input: lines.join('\n') + '\n',
      encoding: 'utf8',
      stdio: ['pipe', 'inherit', 'inherit'],
    },
  )

  const localCount = execFileSync(
    'docker',
    [
      'exec',
      'supabase_db_no-menu-app',
      'psql',
      '-U',
      'postgres',
      '-d',
      'postgres',
      '-Atc',
      'SELECT count(*) FROM public.drink_products;',
    ],
    { encoding: 'utf8' },
  ).trim()
  console.error(`Local drink_products count: ${localCount}`)
}

main()
